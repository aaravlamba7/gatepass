create or replace function public.student_login(p_roll text, p_pass_code text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_student public.students%rowtype; v_token uuid;
begin
  select * into v_student from public.students
  where lower(roll_number) = lower(btrim(p_roll)) and active;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'Roll number or pass code is incorrect.');
  end if;
  if extensions.crypt(coalesce(p_pass_code, ''), v_student.pass_code_hash) <> v_student.pass_code_hash then
    return jsonb_build_object('ok', false, 'error', 'Roll number or pass code is incorrect.');
  end if;
  v_token := gen_random_uuid();
  insert into public.app_sessions (token_hash, role, student_id)
  values (encode(extensions.digest(v_token::text, 'sha256'), 'hex'), 'student', v_student.id);
  return jsonb_build_object('ok', true, 'sessionToken', v_token, 'student', jsonb_build_object(
    'name', v_student.name, 'roll', v_student.roll_number, 'status', v_student.current_status, 'qrToken', v_student.qr_token));
end;
$$;

create or replace function public.guard_login(p_pin text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard public.guards%rowtype; v_token uuid;
begin
  select * into v_guard from public.guards where active order by id limit 1;
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard PIN is incorrect.'); end if;
  if extensions.crypt(coalesce(p_pin, ''), v_guard.pin_hash) <> v_guard.pin_hash then
    return jsonb_build_object('ok', false, 'error', 'Guard PIN is incorrect.');
  end if;
  v_token := gen_random_uuid();
  insert into public.app_sessions (token_hash, role, guard_id)
  values (encode(extensions.digest(v_token::text, 'sha256'), 'hex'), 'guard', v_guard.id);
  return jsonb_build_object('ok', true, 'sessionToken', v_token, 'guard', v_guard.username);
end;
$$;

create or replace function public.student_me(p_session_token uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_student public.students%rowtype;
begin
  select st.* into v_student from public.students st
  join public.app_sessions se on se.student_id = st.id
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'student' and se.expires_at > now() and st.active;
  if not found then return jsonb_build_object('ok', false, 'error', 'Student session expired. Sign in again.'); end if;
  return jsonb_build_object('ok', true, 'student', jsonb_build_object(
    'name', v_student.name, 'roll', v_student.roll_number, 'status', v_student.current_status, 'qrToken', v_student.qr_token));
end;
$$;

create or replace function public.guard_lookup(p_session_token uuid, p_qr_token text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_student public.students%rowtype;
begin
  if not exists (select 1 from public.app_sessions se where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex') and se.role = 'guard' and se.expires_at > now()) then
    return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.');
  end if;
  select * into v_student from public.students where qr_token = btrim(p_qr_token) and active;
  if not found then return jsonb_build_object('ok', false, 'error', 'QR not found. Scan a valid student pass.'); end if;
  return jsonb_build_object('ok', true, 'student', jsonb_build_object(
    'name', v_student.name, 'roll', v_student.roll_number, 'status', v_student.current_status, 'qrToken', v_student.qr_token));
end;
$$;

create or replace function public.guard_record_scan(p_session_token uuid, p_qr_token text, p_movement text, p_id_checked boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard_id bigint; v_student public.students%rowtype; v_movement text;
begin
  select se.guard_id into v_guard_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex') and se.role = 'guard' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.'); end if;
  if p_id_checked is distinct from true then return jsonb_build_object('ok', false, 'error', 'Confirm that you checked the physical college ID.'); end if;
  v_movement := upper(btrim(p_movement));
  if v_movement not in ('ENTRY', 'EXIT') then return jsonb_build_object('ok', false, 'error', 'Select Entry or Exit.'); end if;
  select * into v_student from public.students where qr_token = btrim(p_qr_token) and active for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'QR not found or student is inactive.'); end if;
  if v_movement = 'ENTRY' and v_student.current_status <> 'OUT' then return jsonb_build_object('ok', false, 'error', 'Student is already marked IN.'); end if;
  if v_movement = 'EXIT' and v_student.current_status <> 'IN' then return jsonb_build_object('ok', false, 'error', 'Record Entry before Exit.'); end if;
  update public.students set current_status = case when v_movement = 'ENTRY' then 'IN' else 'OUT' end where id = v_student.id returning * into v_student;
  insert into public.gate_events (student_id, guard_id, movement) values (v_student.id, v_guard_id, v_movement);
  return jsonb_build_object('ok', true, 'movement', v_movement, 'student', jsonb_build_object(
    'name', v_student.name, 'roll', v_student.roll_number, 'status', v_student.current_status, 'qrToken', v_student.qr_token));
end;
$$;

create or replace function public.guard_history(p_session_token uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard_id bigint; v_scans jsonb;
begin
  select se.guard_id into v_guard_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex') and se.role = 'guard' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.'); end if;
  select coalesce(jsonb_agg(jsonb_build_object('name', st.name, 'roll', st.roll_number, 'movement', ev.movement, 'scannedAt', ev.scanned_at) order by ev.scanned_at desc), '[]'::jsonb)
  into v_scans from (select * from public.gate_events order by scanned_at desc limit 20) ev
  join public.students st on st.id = ev.student_id;
  return jsonb_build_object('ok', true, 'scans', v_scans);
end;
$$;

create or replace function public.logout_session(p_session_token uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  delete from public.app_sessions where token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex');
  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.student_login(text, text), public.guard_login(text), public.student_me(uuid), public.guard_lookup(uuid, text), public.guard_record_scan(uuid, text, text, boolean), public.guard_history(uuid), public.logout_session(uuid) from public, anon, authenticated;
grant execute on function public.student_login(text, text), public.guard_login(text), public.student_me(uuid), public.guard_lookup(uuid, text), public.guard_record_scan(uuid, text, text, boolean), public.guard_history(uuid), public.logout_session(uuid) to anon, authenticated;
