-- Campus Gate Pass: shared database backend for GitHub Pages.
-- Run this complete file once in Supabase Dashboard > SQL Editor.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  roll_number text not null unique,
  pass_code_hash text not null,
  qr_token text not null unique,
  current_status text not null default 'OUT' check (current_status in ('IN', 'OUT')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.guards (
  id bigint generated by default as identity primary key,
  username text not null unique,
  pin_hash text not null,
  active boolean not null default true
);

create table if not exists public.app_sessions (
  token_hash text primary key,
  role text not null check (role in ('student', 'guard')),
  student_id bigint references public.students(id),
  guard_id bigint references public.guards(id),
  expires_at timestamptz not null default (now() + interval '8 hours'),
  created_at timestamptz not null default now()
);

create table if not exists public.gate_events (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id),
  guard_id bigint not null references public.guards(id),
  movement text not null check (movement in ('ENTRY', 'EXIT')),
  scanned_at timestamptz not null default now()
);

create index if not exists gate_events_scanned_at_idx on public.gate_events (scanned_at desc);
create index if not exists gate_events_student_idx on public.gate_events (student_id, scanned_at desc);

-- Direct table access is denied. Browser clients may call only the checked functions below.
alter table public.students enable row level security;
alter table public.guards enable row level security;
alter table public.app_sessions enable row level security;
alter table public.gate_events enable row level security;
revoke all on table public.students, public.guards, public.app_sessions, public.gate_events from public, anon, authenticated;

